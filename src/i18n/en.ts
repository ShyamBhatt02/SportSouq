type DeepWiden<T> = T extends (...args: infer A) => infer R
  ? (...args: A) => R
  : T extends readonly (infer U)[]
    ? readonly DeepWiden<U>[]
    : T extends object
      ? { [K in keyof T]: DeepWiden<T[K]> }
      : T extends string
        ? string
        : T;

export type Messages = DeepWiden<typeof en>;
export default en as Messages;
